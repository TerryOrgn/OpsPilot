-- JOB v1 schema baseline for an empty, explicitly selected MySQL 8 schema.
-- Run as a migration account. Initialize the JOB_MONITOR checkpoint separately.

CREATE TABLE `JOB_EXECUTION_LOG` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `EXECUTION_ID` varchar(64) NOT NULL COMMENT 'JOB执行唯一标识',
  `SYSTEM_ID` varchar(50) NOT NULL COMMENT '所属系统',
  `JOB_NAME` varchar(100) NOT NULL COMMENT 'JOB名称',
  `BUSINESS_DATE` date NOT NULL COMMENT '业务日期',
  `START_TIME` datetime(3) NOT NULL COMMENT 'JOB开始时间',
  `END_TIME` datetime(3) DEFAULT NULL COMMENT 'JOB结束时间',
  `STATUS` varchar(20) NOT NULL COMMENT 'RUNNING/SUCCESS/FAILED',
  `ERROR_MESSAGE` text COMMENT '异常信息',
  `CREATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `UPDATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_EXECUTION_ID` (`EXECUTION_ID`),
  KEY `IDX_SYSTEM_JOB_DATE` (`SYSTEM_ID`,`JOB_NAME`,`BUSINESS_DATE`),
  KEY `IDX_STATUS_START` (`STATUS`,`START_TIME`),
  KEY `IDX_JOB_UPDATED_AT` (`UPDATED_AT`,`ID`),
  KEY `IDX_JOB_STATUS_START` (`STATUS`,`START_TIME`),
  CONSTRAINT `job_execution_log_chk_1` CHECK ((`STATUS` in (_utf8mb4'RUNNING',_utf8mb4'SUCCESS',_utf8mb4'FAILED'))),
  CONSTRAINT `job_execution_log_chk_2` CHECK (((`END_TIME` is null) or (`END_TIME` >= `START_TIME`)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='OpsPilot JOB执行日志表';

CREATE TABLE `JOB_ALERT_HISTORY` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '告警记录主键',
  `EXECUTION_ID` varchar(64) NOT NULL COMMENT 'JOB执行唯一标识',
  `SYSTEM_ID` varchar(50) NOT NULL COMMENT '所属系统',
  `JOB_NAME` varchar(100) NOT NULL COMMENT 'JOB名称',
  `ALERT_TYPE` varchar(50) NOT NULL COMMENT '异常类型',
  `ALERT_LEVEL` varchar(20) NOT NULL COMMENT '告警级别',
  `ALERT_MESSAGE` text COMMENT '告警描述',
  `ALERT_STATUS` varchar(20) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/ACKNOWLEDGED/RESOLVED',
  `FIRST_DETECTED_AT` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '首次检测时间',
  `LAST_DETECTED_AT` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '最近检测时间',
  `DETECT_COUNT` int NOT NULL DEFAULT '1' COMMENT '检测到相同异常的次数',
  `RESOLVED_AT` datetime(3) DEFAULT NULL COMMENT '告警解决时间',
  `CREATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `RESOLUTION_TYPE` varchar(30) DEFAULT NULL COMMENT 'AUTO/MANUAL',
  `RESOLUTION_REASON` varchar(500) DEFAULT NULL COMMENT '告警恢复原因',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_EXECUTION_ALERT` (`EXECUTION_ID`,`ALERT_TYPE`),
  KEY `IDX_ALERT_STATUS` (`ALERT_STATUS`,`FIRST_DETECTED_AT`),
  CONSTRAINT `FK_TEST_ALERT_EXECUTION` FOREIGN KEY (`EXECUTION_ID`) REFERENCES `JOB_EXECUTION_LOG` (`EXECUTION_ID`),
  CONSTRAINT `job_alert_history_chk_1` CHECK ((`ALERT_LEVEL` in (_utf8mb4'INFO',_utf8mb4'WARNING',_utf8mb4'CRITICAL'))),
  CONSTRAINT `job_alert_history_chk_2` CHECK ((`ALERT_STATUS` in (_utf8mb4'OPEN',_utf8mb4'ACKNOWLEDGED',_utf8mb4'RESOLVED')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='OpsPilot JOB异常事件记录表';

CREATE TABLE `JOB_ALERT_STATUS_HISTORY` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '审计记录ID',
  `ALERT_ID` bigint NOT NULL COMMENT '关联告警ID',
  `OLD_STATUS` varchar(20) DEFAULT NULL COMMENT '变更前状态',
  `NEW_STATUS` varchar(20) NOT NULL COMMENT '变更后状态',
  `CHANGE_TYPE` varchar(30) NOT NULL COMMENT 'CREATE/ACKNOWLEDGE/AUTO_RESOLVE/MANUAL_RESOLVE',
  `CHANGE_REASON` varchar(500) DEFAULT NULL COMMENT '状态变更原因',
  `OPERATOR_TYPE` varchar(20) NOT NULL COMMENT 'SYSTEM/USER',
  `OPERATOR_ID` varchar(100) DEFAULT NULL COMMENT '操作人员或系统标识',
  `CHANGED_AT` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '状态变更时间',
  PRIMARY KEY (`ID`),
  KEY `IDX_ALERT_ID_TIME` (`ALERT_ID`,`CHANGED_AT`),
  CONSTRAINT `FK_TEST_STATUS_ALERT` FOREIGN KEY (`ALERT_ID`) REFERENCES `JOB_ALERT_HISTORY` (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='OpsPilot JOB告警状态变更审计表';

CREATE TABLE `JOB_MONITOR_CHECKPOINT` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `MONITOR_NAME` varchar(100) NOT NULL COMMENT '监控任务名称',
  `LAST_SCAN_TIME` datetime(3) NOT NULL COMMENT '上次成功扫描水位',
  `LAST_SUCCESS_TIME` datetime(3) DEFAULT NULL COMMENT '上次成功完成扫描的时间',
  `SCAN_STATUS` varchar(20) NOT NULL DEFAULT 'IDLE' COMMENT 'IDLE/RUNNING/SUCCESS/FAILED',
  `LAST_ERROR_MESSAGE` text COMMENT '最近一次扫描失败原因',
  `CREATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_MONITOR_NAME` (`MONITOR_NAME`),
  CONSTRAINT `job_monitor_checkpoint_chk_1` CHECK ((`SCAN_STATUS` in (_utf8mb4'IDLE',_utf8mb4'RUNNING',_utf8mb4'SUCCESS',_utf8mb4'FAILED')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='OpsPilot JOB监控水位表';

CREATE TABLE `JOB_NOTIFICATION_HISTORY` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '通知任务主键',
  `EVENT_ID` bigint NOT NULL COMMENT '关联告警状态变更事件ID',
  `ALERT_ID` bigint NOT NULL COMMENT '关联告警ID',
  `NOTIFICATION_TYPE` varchar(30) NOT NULL DEFAULT 'CONSOLE' COMMENT '通知渠道：CONSOLE/EMAIL/WEBHOOK',
  `NOTIFICATION_STATUS` varchar(20) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/SENT/FAILED',
  `RETRY_COUNT` int NOT NULL DEFAULT '0' COMMENT '已重试次数',
  `LAST_ERROR_MESSAGE` varchar(1000) DEFAULT NULL COMMENT '最近一次发送失败原因',
  `CREATED_AT` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `SENT_AT` datetime(3) DEFAULT NULL,
  `UPDATED_AT` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `PROCESSING_STARTED_AT` datetime(3) DEFAULT NULL COMMENT '通知任务开始处理时间',
  `CLAIM_TOKEN` varchar(36) DEFAULT NULL COMMENT '当前任务领取令牌',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_EVENT_CHANNEL` (`EVENT_ID`,`NOTIFICATION_TYPE`),
  KEY `IDX_NOTIFICATION_STATUS` (`NOTIFICATION_STATUS`,`CREATED_AT`),
  KEY `FK_TEST_NOTIFICATION_ALERT` (`ALERT_ID`),
  CONSTRAINT `FK_TEST_NOTIFICATION_ALERT` FOREIGN KEY (`ALERT_ID`) REFERENCES `JOB_ALERT_HISTORY` (`ID`),
  CONSTRAINT `FK_TEST_NOTIFICATION_EVENT` FOREIGN KEY (`EVENT_ID`) REFERENCES `JOB_ALERT_STATUS_HISTORY` (`ID`),
  CONSTRAINT `job_notification_history_chk_1` CHECK ((`NOTIFICATION_STATUS` in (_utf8mb4'PENDING',_utf8mb4'PROCESSING',_utf8mb4'SENT',_utf8mb4'FAILED',_utf8mb4'EXHAUSTED'))),
  CONSTRAINT `job_notification_history_chk_2` CHECK ((`RETRY_COUNT` >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='OpsPilot JOB告警通知任务表';
